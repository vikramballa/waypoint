function makeTask(seed: TaskSeed, index: number): Task {
  const project = seed.project;
  const assignee = seed.assignee ?? null;
  const due = seed.due == null ? null : d(seed.due);
  const start =
    seed.start != null ? d(seed.start) : due ? addDays(due, seed.milestone ? 0 : -3) : null;
  const followers = new Set<ID>(["u-maya"]);
  if (assignee) followers.add(assignee);
  const customFields: Record<ID, unknown> = {};
  if (seed.effort != null) customFields["fld-effort"] = seed.effort;
  if (seed.stage) customFields["fld-stage"] = seed.stage;
  if (seed.budget != null) customFields["fld-budget"] = seed.budget;
  if (seed.reviewed != null) customFields["fld-reviewed"] = seed.reviewed;
  if (seed.requester) customFields["fld-requester"] = [seed.requester];
  if (seed.priority) {
    customFields["fld-priority"] =
      seed.priority === "high" ? "po-high" : seed.priority === "medium" ? "po-medium" : "po-low";
  }

  return {
    id: seed.id,
    name: seed.name,
    notes: seed.notes ?? "",
    completed: Boolean(seed.completed),
    completedAt: seed.completed ? stamp(60 * 24 * 3) : null,
    assigneeId: assignee,
    creatorId: "u-maya",
    projectId: project,
    sectionId: seed.section,
    parentId: null,
    dueDate: due,
    dueTime: null,
    startDate: start,
    order: (index + 1) * 1000,
    priority: seed.priority ?? null,
    tagIds: seed.tags ?? [],
    followerIds: [...followers],
    customFields: customFields as Task["customFields"],
    blockedByIds: seed.blockedBy ?? [],
    blockingIds: [],
    attachments: [],
    likeUserIds: Array.from({ length: seed.likeCount ?? 0 }, (_, i) => users[(i + 1) % users.length].id),
    createdAt: stamp(60 * 24 * (20 + index)),
    modifiedAt: stamp(60 * (index + 1)),
    milestone: seed.milestone,
  };
}

